/** Short words for the packet table: TEXT_MESSAGE_APP -> 'text', WAYPOINT_APP -> 'waypoint'. */
export function portLabel(portnum: number): string {
  if (portnum === PortNum.Text) return 'text'
  const name = PORTNUM_NAMES[portnum]
  return name ? name.replace(/_APP$/, '').replace(/_/g, '-').toLowerCase() : 'app'
}

